/**
 * Source of translations/index.js: a static table of dynamic imports.
 *
 * A consumer cannot write import(`pkg/translations/${locale}.js`) itself:
 * bundlers only expand a templated import for relative paths. The static
 * table lets them split every locale into its own lazy chunk.
 */
// Locale names end up in generated code and in import paths.
const LOCALE_NAME = /^[A-Za-z0-9]+(?:[-_][A-Za-z0-9]+)*$/;

export function renderTranslationsIndex(locales) {
  for (const locale of locales) {
    if (!LOCALE_NAME.test(locale)) {
      throw new Error(`Unexpected locale name ${JSON.stringify(locale)}`);
    }
  }

  const entries = [...locales]
    .sort()
    .map((locale) => `  [${JSON.stringify(locale)}, () => import(${JSON.stringify(`./${locale}.js`)})],`)
    .join('\n');

  return `/**
 * Auto-generated by bin/build-ckeditor-translations.mjs
 * Do not edit manually.
 */
const loaders = new Map([
${entries}
]);

/**
 * Loads the CKEditor UI translation for a locale and resolves with the
 * name it is registered under, which is what the editor's \`language.ui\`
 * must be set to. Applications tend to write zh-CN where CKEditor names
 * its files zh-cn, so the lower-cased name is tried as well. Rejects when
 * the build has no translation for either.
 */
export async function loadTranslation(locale) {
  const name = [locale, locale.toLowerCase()].find((candidate) => loaders.has(candidate));

  if (name === undefined) {
    throw new Error(\`No CKEditor translation for locale "\${locale}"\`);
  }

  await loaders.get(name)();

  return name;
}
`;
}

export const TRANSLATIONS_INDEX_DTS = `/**
 * Loads the CKEditor UI translation for a locale and resolves with the
 * name it is registered under, which is what the editor's \`language.ui\`
 * must be set to. The lower-cased name is tried as well (zh-CN finds
 * zh-cn). Rejects when the build has no translation for either.
 */
export declare function loadTranslation(locale: string): Promise<string>;
`;
